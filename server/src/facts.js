'use strict';
const MARKER=/〔待确认[:：]([^〕]+)〕/g;

/**
 * 判定一个〔待确认〕占位符是不是"只有用户能提供的事实"。
 *
 * 设计原则（比"枚举所有写作任务"更鲁棒）：
 * 真实招标文件千变万化，不可能穷举"AI 该写的内容"，但可以穷举"必须由用户提供的
 * 客观事实"的语义类别。判错两个方向的代价不对称：
 *   - 误判为"AI 该写" → 逼模型编造事实（编造业绩、编造现场条件），风险高
 *   - 误判为"用户该给" → 多问用户一句，风险低
 * 所以这里宁可放宽，只拦"明显的写作任务"（见 isWritingTask）。
 */
function needsUser(key){
  const k = String(key || '');
  return (
    // 业绩与合同事实
    /类似.{0,6}(?:业绩|经历|项目)|合同(?:金额|签订|工期|编号)|中标(?:通知|金额)|业绩/.test(k) ||
    // 供应商与人员安排
    /供应商.{0,6}(?:入场|进场|名称)|人员来源|(?:项目经理|技术负责人|安全员|特种作业|管理人员|劳动力|机械|设备).{0,10}(?:到场|进场|入场|配备|配置|数量|型号)/.test(k) ||
    // 现场实测与既有条件
    /(?:现场|现状|既有|原有|实际).{0,12}(?:容量|接口|条件|情况|现状|尺寸|位置|标高|数量|规格|型号|年限|结构|负荷|管径|路由)/.test(k) ||
    /(?:建成|竣工|启用).{0,4}(?:年代|年份|时间)|房屋结构|结构形式|建筑面积实测|场地(?:面积|条件)/.test(k) ||
    /(?:踏勘|查勘|勘查|实测|实测值)/.test(k) ||
    /临时(?:用电|用水|用地).{0,6}(?:容量|接口|位置|条件|批复)/.test(k) ||
    // 外部方约束
    /(?:甲方|业主|招标人|建设单位).{0,10}(?:平台|接口|要求|指定|提供|确认)/.test(k) ||
    /平台.{0,8}(?:协议|接口|对接)|第三方.{0,6}(?:接口|协议|配合)/.test(k) ||
    // 企业与资质事实
    /资质|证书|许可证|社保|财务|信用|注册资金|人员职称/.test(k) ||
    // 居民与外部协调
    /居民|住户|业主.{0,4}(?:配合|意愿|同意)|拆迁|腾退|占道|断路|停电|停水/.test(k) ||
    // 项目周边环境（现场才能确认，AI 无从得知）
    /(?:就近|周边|附近|邻近|沿线|相邻).{0,12}(?:医院|学校|居民|道路|建筑|管线|设施|单位|敏感点|距离|位置)/.test(k)
  );
}

/**
 * 明显的写作任务：段落数、图表数、步骤数、检查频次、责任岗位、方案流程等。
 * 这些必须由 AI 自己写，出现〔待确认〕即视为推卸。
 */
function isWritingTask(key){
  const k = String(key || '');
  return (
    /(?:段落|图表|表格|插图|附图|字数|篇幅|页数|章节).{0,6}(?:数量|条数|个数|多少)?/.test(k) ||
    /(?:工作)?步骤.{0,6}(?:数量|条数|划分)/.test(k) ||
    /(?:检查|巡查|检测|维护|培训|演练).{0,4}(?:频次|周期|次数|间隔)/.test(k) ||
    /(?:责任人|负责岗位|岗位职责|职责分工)/.test(k) ||
    /(?:技术路线|工艺流程|施工方法|实施方案|管理措施|保证措施|控制措施).{0,6}(?:选择|确定|编写|内容)?/.test(k) ||
    /(?:目标值|指标值|验收标准|控制标准)/.test(k) ||
    // 技术指标类：投标阶段应按招标文件与规范写明，不能推给"施工图明确"
    /(?:压实度|厚度|强度等级|电阻|绝缘|限值|允许偏差|坡率|埋深|管径|标高|间距|配比|掺量|含水率|坍落度|保护层)/.test(k) ||
    /(?:审查|审批|备案|验收).{0,6}(?:周期|时限|流程)/.test(k)
  );
}

/**
 * 投标人自己拟定即可的计划类内容：拟投入的机械/人员配置、供应商与入场计划、
 * 移交界面，以及模型惯用的「以…为准 / 按…确定」这类含糊收尾。
 *
 * 这类东西在投标阶段本来就不存在唯一正确答案，投标人写多少就是多少，
 * 让用户去填反而填不出来——归 AI 写实，不算推卸，也不进待补字段。
 * 与 needsUser 冲突时本函数优先（业绩、资质、合同金额等硬事实不在此列）。
 */
function isPlanHedge(key){
  const k = String(key || '');
  return (
    /拟(?:投入|配置|配备|安排|派|组建)/.test(k) ||
    /(?:人员|劳动力|机械|设备|材料|仪器|工器具).{0,10}(?:配置|配备|清单|数量|台数)/.test(k) ||
    /(?:供应商|分包|劳务).{0,8}(?:清单|数量|配置|入场计划|进场计划)/.test(k) ||
    /(?:入场|进场).{0,6}计划/.test(k) ||
    /(?:移交|交接).{0,8}(?:条件|界面|标准)/.test(k) ||
    /以.{0,12}为准|按.{0,14}(?:确定|执行|调整)/.test(k)
  );
}

module.exports={MARKER,needsUser,isWritingTask,isPlanHedge};
